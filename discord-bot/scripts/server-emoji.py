def blank():
    return [["."] * 16 for _ in range(16)]


def verified():
    g = blank()
    for y in range(16):
        for x in range(16):
            dx, dy = abs(x - 7.5), abs(y - 7.5)
            if max(dx, dy) <= 5 or dx + dy <= 7.5:
                g[y][x] = "v"
    for x, y in [(4, 7), (4, 8), (5, 8), (5, 9), (6, 9), (6, 10), (7, 9), (7, 8), (8, 8), (8, 7), (9, 7), (9, 6), (10, 6), (10, 5), (11, 5)]:
        g[y][x] = "W"
    return g


def seg_dist(px, py, ax, ay, bx, by):
    vx, vy = bx - ax, by - ay
    t = max(0, min(1, ((px - ax) * vx + (py - ay) * vy) / (vx * vx + vy * vy)))
    return math.hypot(px - ax - t * vx, py - ay - t * vy)


def wrench():
    g = blank()
    for y in range(16):
        for x in range(16):
            if seg_dist(x, y, 3, 12, 10, 5) <= 1.1 or math.hypot(x - 2.5, y - 12.5) <= 1.6:
                g[y][x] = "s"
            hx, hy = x - 11, y - 4
            if math.hypot(hx, hy) <= 3.1:
                along = (hx - hy) / math.sqrt(2)
                across = abs(hx + hy) / math.sqrt(2)
                if not (along > 0.3 and across < 1.2):
                    g[y][x] = "s"
    return g


def pickaxe():
    g = blank()
    for y in range(16):
        for x in range(16):
            if 2 <= x <= 10 and x + y in (15, 16):
                g[y][x] = "n"
            d = math.hypot(x - 2, y - 13)
            ang = math.degrees(math.atan2(13 - y, x - 2))
            if 10.2 <= d <= 12.2 and 8 <= ang <= 82:
                g[y][x] = "v"
    return g


def parse(s):
    rows = [list(r) for r in s.strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), s
    return rows


def hexc(h):
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def render(g):
    colors = [[None] * 16 for _ in range(16)]
    for x in range(16):
        y = 0
        while y < 16:
            ch = g[y][x]
            if ch in SHADED:
                end = y
                while end < 16 and g[end][x] == ch:
                    end += 1
                light, mid, dark = SHADED[ch]
                n = end - y
                for i in range(n):
                    if n >= 3 and i == 0:
                        c = light
                    elif n >= 2 and i == n - 1:
                        c = dark
                    else:
                        c = mid
                    colors[y + i][x] = c
                y = end
            else:
                if ch != ".":
                    colors[y][x] = FLAT[ch]
                y += 1
    for y in range(16):
        for x in range(16):
            if colors[y][x] is None and any(
                0 <= x + dx < 16 and 0 <= y + dy < 16 and g[y + dy][x + dx] not in ".D"
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))
            ):
                colors[y][x] = FLAT["D"]
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y in range(16):
        for x in range(16):
            if colors[y][x]:
                im.putpixel((x, y), hexc(colors[y][x]))
    return im.resize((SIZE, SIZE), Image.NEAREST)


