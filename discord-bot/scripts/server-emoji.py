def bee(src):
    im = Image.open(src).convert("RGBA")
    im = im.crop(im.getbbox())
    im.thumbnail((SIZE, SIZE), Image.LANCZOS)
    out = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    out.paste(im, ((SIZE - im.width) // 2, (SIZE - im.height) // 2), im)
    return out


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    for name, s in ART.items():
        render(parse(s)).save(OUT / f"{name}.png")
    for name, fn in (("verified", verified), ("wrench", wrench), ("pickaxe", pickaxe)):
        render(fn()).save(OUT / f"{name}.png")
    for f in (BOT / "assets" / "emoji").glob("*.png"):
        shutil.copy(f, OUT / f.name)
    for src, name in BEES.items():
        bee(ROOT / "public" / "bee" / f"{src}.webp").save(OUT / f"{name}.png", optimize=True)
    subprocess.run(["magick", "-background", "none", "-density", "300", str(ROOT / "public" / "logo.svg"),
                    "-resize", f"{SIZE}x{SIZE}", str(OUT / "logo.png")], check=True)
    files = sorted(OUT.glob("*.png"))
    print(len(files), "emoji")
    if len(files) > 50:
        sys.exit("more than 50 static emoji")


main()
